import pandas as pd

import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import re
import nltk
from nltk.corpus import stopwords
from nltk.tokenize import word_tokenize
from nltk.stem import WordNetLemmatizer
from collections import Counter
from wordcloud import WordCloud

nltk.download('punkt')
nltk.download('punkt_tab')
nltk.download('stopwords')
nltk.download('wordnet')
nltk.download('omw-1.4')
sns.set_theme(style='whitegrid')
plt.rcParams['figure.figsize'] = (10,6)

df = pd.read_csv('IMDB Dataset.csv')

print(df.head())

print(df.shape)

print(df.isnull().sum())

print(df.info())

plt.figure(figsize=(6, 4))
sns.countplot(x='sentiment', data=df, hue='sentiment', palette='viridis', legend=False)
plt.title('Distribution of Sentiments (Positive vs Negative)')
plt.xlabel('Sentiment')
plt.ylabel('Count')
plt.show()

df['char_count'] = df['review'].apply(len)
df['word_count'] = df['review'].apply(lambda x : len(x.split()))

print(df[['char_count','word_count']].describe())

plt.figure(figsize=(10,5))
sns.histplot(df['word_count'],bins=50,kde = True,color = 'purple')
plt.title('Distribution of Review Word Counts')
plt.xlabel('Number of Words')
plt.ylabel('Frequency')
plt.show()

lemmatizer = WordNetLemmatizer()

stop_words = set(stopwords.words('english'))

def preprocess_text(text):
  text = re.sub(r'<.*?>','',text)
  text = re.sub(r'http\S+|www\S+|https\S+', '',text,flags = re.MULTILINE)
  text = re.sub(r'[^a-zA-Z\s]','',text)
  text = text.lower()
  tokens = word_tokenize(text)
  cleaned_tokens = [
      lemmatizer.lemmatize(token)
      for token in tokens
      if token not in stop_words and len(token)>2
  ]
  return ' '.join(cleaned_tokens)

df['cleaned_review'] = df['review'].apply(preprocess_text)
print("Preprocessing Complted......")

print("Before and after Preprocessing...")
print("Original : ",df['review'].iloc[0][:300],"....\n")
print("Cleaned : ",df['cleaned_review'].iloc[0][:300],"....\n")

all_words = ' '.join(df['cleaned_review']).split()

word_counts = Counter(all_words)

common_words = word_counts.most_common(20)
words_df = pd.DataFrame(common_words,columns=['Word','Frequency'])

plt.figure(figsize=(12,6))
sns.barplot(x='Frequency',y='Word',data=words_df,palette='magma')
plt.title('Top 20 Most Frequent Words after Preprocessing')
plt.xlabel('Frequency')
plt.ylabel('Words')
plt.show()

wordcloud = WordCloud(width=800, height=400, background_color='white', max_words=150).generate(' '.join(df['cleaned_review']))
plt.figure(figsize=(12,6))
plt.imshow(wordcloud,interpolation = 'bilinear')
plt.axis('off')
plt.title('Word Cloud of Cleaned IMDB Reviews ',fontsize = 16)
plt.show()

